import test from "node:test";
import assert from "node:assert/strict";
import { once } from "node:events";
import { createRequire } from "node:module";
import path from "node:path";
import express from "express";
import { createSaaSRouter } from "../concepts/67-multi-tenant-saas.js";
import { SaaS } from "./architecture.js";

const require = createRequire(import.meta.url);
const { chromium } = createRequire(require.resolve("@playwright/mcp/package.json"))("playwright") as typeof import("playwright");
test("browser switches tenants, runs guided conversations, rejects foreign reads and enforces roles and quotas", { timeout: 60000 }, async () => {
  const app = express(); app.use(express.json());
  app.use("/api/c67", createSaaSRouter(new SaaS(), async () => { throw new Error("No model calls in smoke tests"); }));
  app.use(express.static(path.resolve("dist")));
  const server = app.listen(0, "127.0.0.1"); await once(server, "listening");
  const address = server.address(); assert.ok(address && typeof address === "object");
  let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  try {
    browser = await chromium.launch({ channel: "chrome", headless: true,
      ...(process.env.PLAYWRIGHT_MCP_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_MCP_EXECUTABLE_PATH } : {}) });
    const page = await browser.newPage(), errors: string[] = [];
    const consoleErrors: string[] = [], failedResponses: string[] = [];
    page.on("pageerror", (error) => errors.push(error.message));
    page.on("console", (message) => { if (message.type() === "error") consoleErrors.push(message.text()); });
    page.on("response", (response) => { if (response.status() >= 400) failedResponses.push(response.url()); });
    await page.goto(`http://127.0.0.1:${address.port}/?lesson=67`);
    await page.getByText("Workspace: acme · User: alice · Role: admin", { exact: true }).waitFor();
    // Another client creates data; Refresh must fetch it rather than only show a notice.
    const external = await page.request.post(`http://127.0.0.1:${address.port}/api/c67/sessions`, { headers: { Authorization: "Bearer lesson67-alice" }, data: {} });
    assert.equal(external.status(), 201);
    const externalSession = await external.json();
    let release!: () => void;
    const gate = new Promise<void>((resolve) => { release = resolve; });
    await page.route("**/api/c67/workspace", async (route) => { await gate; await route.continue(); });
    await page.getByRole("button", { name: "Refresh workspace", exact: true }).click();
    const refreshing = page.getByRole("button", { name: "Refreshing workspace…", exact: true });
    await refreshing.waitFor(); assert.equal(await refreshing.isDisabled(), true);
    release();
    await page.getByRole("status").filter({ hasText: "Refresh #1 completed" }).waitFor();
    assert.equal(await page.locator(`#saas-session option[value="${externalSession.id}"]`).count(), 1);
    await page.unroute("**/api/c67/workspace");
    await page.getByRole("button", { name: "Refresh workspace", exact: true }).click();
    await page.getByRole("status").filter({ hasText: "Refresh #2 completed" }).waitFor();
    assert.match(await page.getByRole("status").filter({ hasText: "Refresh #2 completed" }).innerText(), /0\/5 accepted runs/);
    let releaseAccess!: () => void;
    const accessGate = new Promise<void>((resolve) => { releaseAccess = resolve; });
    await page.route("**/api/c67/access-check", async (route) => { await accessGate; await route.continue(); });
    await page.getByRole("button", { name: "Read project", exact: true }).click();
    await page.getByRole("button", { name: "Reading project…", exact: true }).waitFor();
    assert.equal(await page.getByRole("button", { name: "Reading project…", exact: true }).isDisabled(), true);
    await page.locator("#saas-project-result").filter({ hasText: "Checking project access…" }).waitFor();
    releaseAccess();
    await page.locator("#saas-project-result").filter({ hasText: "Access denied (404)" }).waitFor();
    await page.unroute("**/api/c67/access-check");
    await page.locator("#saas-project").fill("acme-roadmap");
    await page.getByRole("button", { name: "Read project", exact: true }).click();
    await page.locator("#saas-project-result").filter({ hasText: "Authorized read: Acme confidential roadmap" }).waitFor();
    await page.getByRole("button", { name: "Read project", exact: true }).click();
    await page.locator("#saas-project-result").filter({ hasText: "Check #3" }).waitFor();
    await page.getByRole("button", { name: "Create conversation", exact: true }).click();
    await page.getByText(/^Conversation ID:/).waitFor();
    const id = await page.locator("#saas-session").inputValue();
    await page.locator("#saas-foreign-session").fill(id);
    await page.getByRole("button", { name: "Check conversation access", exact: true }).click();
    await page.locator("#saas-session-result").filter({ hasText: `Authorized conversation: ${id}` }).waitFor();
    const run = page.getByRole("button", { name: "Run guided (no model API)", exact: true });
    await run.click();
    await page.getByText("Run completed; conversation and tenant usage updated.", { exact: true }).waitFor();
    await page.getByText(/Tenant-scoped list_projects returned: Acme confidential/).waitFor();
    await page.locator("#saas-account").selectOption("lesson67-bob");
    await page.getByText("Workspace: orbit · User: bob · Role: admin", { exact: true }).waitFor();
    assert.equal(await page.getByText(/Tenant-scoped list_projects returned: Acme confidential/).count(), 0);
    await page.locator("#saas-foreign-session").fill(id);
    await page.getByRole("button", { name: "Check conversation access", exact: true }).click();
    await page.locator("#saas-session-result").filter({ hasText: "Access denied (404)" }).waitFor();
    await page.locator("#saas-foreign-session").fill("luis coco enriquez");
    await page.getByRole("button", { name: "Check conversation access", exact: true }).click();
    await page.locator("#saas-session-result").filter({ hasText: "Access denied (404)" }).waitFor();
    await page.locator("#saas-foreign-session").fill("11233");
    await page.getByRole("button", { name: "Check conversation access", exact: true }).click();
    await page.locator("#saas-session-result").filter({ hasText: 'Access denied (404) for ID "11233"' }).waitFor();
    assert.match(await page.locator("#saas-session-result").innerText(), /generated conversation UUID/);
    assert.deepEqual(failedResponses, []);
    assert.deepEqual(consoleErrors, []);
    assert.equal(await page.getByRole("alert").count(), 0);
    await page.route("**/api/c67/access-check", (route) => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ message: "Temporarily unavailable" }) }));
    await page.getByRole("button", { name: "Check conversation access", exact: true }).click();
    await page.locator("#saas-session-result").filter({ hasText: "Access check failed:" }).waitFor();
    assert.equal(await page.locator("#saas-session-result").getAttribute("role"), "alert");
    assert.equal(await page.getByRole("button", { name: "Check conversation access", exact: true }).isEnabled(), true);
    await page.unroute("**/api/c67/access-check");
    await page.getByRole("button", { name: "Check conversation access", exact: true }).click();
    await page.locator("#saas-session-result").filter({ hasText: "Access denied (404)" }).waitFor();
    // Failed refreshes must report failure locally, preserve data and allow retry.
    await page.route("**/api/c67/workspace", (route) => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ message: "Temporarily unavailable" }) }));
    await page.getByRole("button", { name: "Refresh workspace", exact: true }).click();
    await page.getByRole("alert").filter({ hasText: "Refresh failed:" }).waitFor();
    assert.equal(await page.getByRole("button", { name: "Refresh workspace", exact: true }).isEnabled(), true);
    await page.getByText("Workspace: orbit · User: bob · Role: admin", { exact: true }).waitFor();
    await page.unroute("**/api/c67/workspace");
    await page.getByRole("button", { name: "Refresh workspace", exact: true }).click();
    await page.getByRole("status").filter({ hasText: "Refresh #1 completed" }).waitFor();
    assert.equal(await page.getByRole("alert").count(), 0);
    await page.locator("#saas-account").selectOption("lesson67-ava");
    await page.getByText("Workspace: acme · User: ava · Role: viewer", { exact: true }).waitFor();
    await page.getByRole("button", { name: "Create conversation", exact: true }).click();
    await page.getByRole("alert").filter({ hasText: "HTTP 403" }).waitFor();
    await page.locator("#saas-account").selectOption("lesson67-alice");
    await page.getByText("Workspace: acme · User: alice · Role: admin", { exact: true }).waitFor();
    await page.locator("#saas-session").selectOption(id);
    failedResponses.length = 0; consoleErrors.length = 0;
    for (let i = 2; i <= 5; i++) {
      await run.click(); await page.getByText(new RegExp(`Accepted runs: ${i}/5`)).waitFor();
    }
    await page.locator("#saas-run-availability").filter({ hasText: "Tenant run quota reached (5/5)" }).waitFor();
    assert.equal(await run.isDisabled(), true);
    assert.equal(await page.getByRole("button", { name: "Run live agent (billed)", exact: true }).isDisabled(), true);
    // Simulate stale browser usage after another client consumes the last slot.
    const stale = await (await page.request.get(`http://127.0.0.1:${address.port}/api/c67/workspace`, { headers: { Authorization: "Bearer lesson67-alice" } })).json();
    stale.usage.runs = 4;
    await page.route("**/api/c67/workspace", (route) => route.fulfill({ contentType: "application/json", body: JSON.stringify(stale) }));
    await page.getByRole("button", { name: "Refresh workspace", exact: true }).click();
    await page.locator("#saas-run-availability").filter({ hasText: "1 accepted runs remaining" }).waitFor();
    await page.unroute("**/api/c67/workspace");
    await run.click(); await page.getByRole("status").filter({ hasText: "Run not started (429)" }).waitFor();
    await page.locator("#saas-run-availability").filter({ hasText: "Tenant run quota reached (5/5)" }).waitFor();
    assert.equal(await run.isDisabled(), true);
    assert.deepEqual(failedResponses, []); assert.deepEqual(consoleErrors, []);
    await page.getByRole("button", { name: "Load source code", exact: true }).click();
    await page.locator("summary").filter({ hasText: /^architecture.ts$/ }).waitFor();
    assert.deepEqual(errors, []);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  } finally {
    await browser?.close();
    await new Promise<void>((resolve) => { server.close(() => resolve()); server.closeAllConnections(); });
  }
});
